 * occurrence's own id, which is the detail that makes it work.
 * RecurrenceMaterialiser rewrites an event's occurrence rows wholesale on every
 * write, so a foreign key to one would cascade this record away every time
 * somebody corrected a title — and the alert would fire again on the next sweep.
 * The recurrence id is the instance's identity: where the rule put it before
 * anything moved it, and stable across every re-materialisation.
 *
