 * whole reason that column is jsonb rather than a set of hand-picked fields — an
 * alert round-trips to Google, Graph and CalDAV because it is stored in the
 * vocabulary those three convert to, not because plMail invented a column for
 * it. Nothing queries an alert's offset, so nothing is projected out.
 *
 * What does need a table is the fact that one has fired. An alert must go off
 * exactly once, and every way of losing that is a way that happens in
 * production: two sweeps overlapping when the first ran long, the scheduler
