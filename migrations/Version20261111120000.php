 *     saved with an http:// address becomes a row allowed plain http too, so a
 *     connection that worked yesterday keeps working. Its row also exempts that
 *     host from the private-network rule, which is the one thing this grants
 *     that the old switch did not; the row is on the admin page to be removed.
 *
 * Read from $_SERVER, which holds the real environment and, through
 * config/bootstrap_generated_secrets.php, the generated secrets file — the same
